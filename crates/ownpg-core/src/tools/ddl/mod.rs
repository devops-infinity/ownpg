pub fn routes() -> Result<Vec<Route>> {
    let mut routes = table::routes()?;
    routes.extend(index::routes()?);
    routes.extend(routine::routes()?);
    routes.extend(types::routes()?);
    Ok(routes)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn toggles_and_numbers_parse() {
        assert_eq!(Toggle::Unset.as_bool(), None);
        assert_eq!(Toggle::On.as_bool(), Some(true));
        assert_eq!(number("start", " 10 ").unwrap(), Some(10));
        assert_eq!(number("start", "").unwrap(), None);
        assert!(number("start", "ten").is_err());
        assert_eq!(decimal("cost", "1.5").unwrap(), Some(1.5));
        assert!(decimal("cost", "inf").is_err());
    }

    #[test]
    fn every_missing_field_is_named_at_once() {
        let mut missing = Missing::new();
        missing
            .need("new_type", false)
            .need("using", true)
            .need("column", false);
        let error = missing.finish("alter_type").unwrap_err();
        let text = error.to_string();
        assert!(text.contains("new_type"));
        assert!(text.contains("column"));
        assert!(!text.contains("using"));
        assert!(Missing::new().finish("x").is_ok());
    }
}
